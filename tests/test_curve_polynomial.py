"""Exact samples exercise cached curve coefficients and short key intervals."""
from array import array
import struct

import pytest
from infernux import AnimationCurve,Keyframe,WrapMode


@pytest.mark.parametrize('left,right,time,bits', [
    ((-.8541792035102844,32.930511474609375,-69.33159637451172),
     (-.8101045489311218,-32.771568298339844,-35.604713439941406),-.8519754409790039,1107380140),
    ((-9.335729598999023,46.14727783203125,-99.09256744384766),
     (-9.128927230834961,-19.932497024536133,95.11138916015625),-9.180627822875977,-1051371400),
    ((-3.7861151695251465,-2.048628091812134,25.617765426635742),
     (-3.771915912628174,.8476276993751526,-11.727453231811523),-3.7832753658294678,-1076295834),
    ((9.945021629333496,-7.026381015777588,-54.23567581176758),
     (28.880508422851562,-34.021400451660156,-82.90560913085938),19.412765502929688,1111316496),
    ((-.008729105815291405,-417583.875,-.0036757427733391523),
     (-.008696835488080978,-263.4327087402344,5213.03466796875),-.008708866313099861,-927581096),
    ((-.008729105815291405,-417583.875,-.0036757427733391523),
     (-.008696835488080978,-263.4327087402344,5213.03466796875),-.008727934211492538,-926166868),
    ((.0010905207600444555,.009796755388379097,1.361811641231725e-8),
     (.016751164570450783,7862.70654296875,-1545623.75),.0074797156266868114,1168366585),
    ((-.06738045811653137,-47.72688293457031,1.1436350177973509e-7),
     (13.32857608795166,3.358887923354814e-8,.009280549362301826),3.050326108932495,-1037780935),
])
def test_single_list_and_buffer_samples_keep_the_same_float32_result(left,right,time,bits):
    curve=AnimationCurve(Keyframe(left[0],left[1],0,left[2]),Keyframe(right[0],right[1],right[2],0),
                         pre_wrap_mode=WrapMode.CLAMP_FOREVER,post_wrap_mode=WrapMode.CLAMP_FOREVER)
    expected=struct.pack('i',bits)
    assert struct.pack('f',curve.evaluate(time))==expected
    assert all(struct.pack('f',v)==expected for v in curve.evaluate_many([time,time]))
    result=array('d',[0,0])
    curve.evaluate_into(array('d',[time,time]),result)
    assert all(struct.pack('f',v)==expected for v in result)
